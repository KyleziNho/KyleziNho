export const glyph = (ch) => G[ch.toUpperCase()] ?? G[' ']
export const glyphWidth = (ch) => glyph(ch)[0].length

// Returns one <path> "d" per character, plus the advance of each, at pixel size px.
export function layout(text, px, gap = 1) {
  let x = 0
  const chars = []
  for (const ch of text) {
    const rows = glyph(ch)
    let d = ''
    rows.forEach((row, ry) => {
      // merge horizontal runs into single rects
      let rx = 0
      while (rx < row.length) {
        if (row[rx] !== '#') { rx++; continue }
        let end = rx
        while (row[end] === '#') end++
        d += `M${x + rx * px} ${ry * px}h${(end - rx) * px}v${px}h-${(end - rx) * px}z`
        rx = end
      }
    })
    chars.push({ ch, x, d, w: rows[0].length * px })
    x += (rows[0].length + gap) * px
  }
  return { chars, width: x - gap * px, height: 7 * px }
}
